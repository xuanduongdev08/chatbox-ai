export function translate(lang, key, vars) {
  const str = (DICT[lang] && DICT[lang][key]) ?? DICT.vi[key] ?? key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}
